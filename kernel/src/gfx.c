static uint32_t *fb;
static uint32_t width;
static uint32_t height;
static uint64_t pitch;

void gfx_init(struct limine_framebuffer *info) {
    fb = info->address;
    width = (uint32_t)info->width;
    height = (uint32_t)info->height;
    pitch = info->pitch;
}

uint32_t gfx_width(void) {
    return width;
}

uint32_t gfx_height(void) {
    return height;
}

void gfx_pixel(int x, int y, uint32_t color) {
    if (x < 0 || y < 0 || (uint32_t)x >= width || (uint32_t)y >= height) {
        return;
    }
    uint8_t *row = (uint8_t *)fb + (uint64_t)y * pitch;
    ((uint32_t *)row)[x] = color;
}

void gfx_fill(int x, int y, int w, int h, uint32_t color) {
    if (w <= 0 || h <= 0) {
        return;
    }
    int x1 = x + w;
    int y1 = y + h;
    if (x < 0) {
        x = 0;
    }
    if (y < 0) {
        y = 0;
    }
    if (x1 > (int)width) {
        x1 = (int)width;
    }
    if (y1 > (int)height) {
        y1 = (int)height;
    }
    for (int py = y; py < y1; py++) {
        uint8_t *row = (uint8_t *)fb + (uint64_t)py * pitch;
        uint32_t *px = (uint32_t *)row;
        for (int xx = x; xx < x1; xx++) {
            px[xx] = color;
        }
    }
}

void gfx_rect(int x, int y, int w, int h, uint32_t color) {
    gfx_fill(x, y, w, 1, color);
    gfx_fill(x, y + h - 1, w, 1, color);
    gfx_fill(x, y, 1, h, color);
    gfx_fill(x + w - 1, y, 1, h, color);
}

static unsigned glyph_index(char c) {
    if (c >= 0x20 && c <= 0x7E) {
        return (unsigned)(c - 0x20);
    }
    return 0;
}

void gfx_char(int x, int y, char c, uint32_t fg, uint32_t bg) {
    unsigned idx = glyph_index(c);
    for (int gy = 0; gy < 8; gy++) {
        uint8_t bits = font8x8[idx][gy];
        for (int gx = 0; gx < 8; gx++) {
            uint32_t color = (bits & (1u << gx)) ? fg : bg;
            gfx_pixel(x + gx, y + gy * 2, color);
            gfx_pixel(x + gx, y + gy * 2 + 1, color);
        }
    }
}

void gfx_char_trans(int x, int y, char c, uint32_t fg) {
    unsigned idx = glyph_index(c);
    for (int gy = 0; gy < 8; gy++) {
        uint8_t bits = font8x8[idx][gy];
        for (int gx = 0; gx < 8; gx++) {
            if (bits & (1u << gx)) {
                gfx_pixel(x + gx, y + gy * 2, fg);
                gfx_pixel(x + gx, y + gy * 2 + 1, fg);
            }
        }
    }
}

void gfx_text(int x, int y, const char *s, uint32_t fg, uint32_t bg) {
    while (*s) {
        gfx_char(x, y, *s++, fg, bg);
        x += 8;
    }
}

void gfx_text_trans(int x, int y, const char *s, uint32_t fg) {
    while (*s) {
        gfx_char_trans(x, y, *s++, fg);
        x += 8;
    }
}
