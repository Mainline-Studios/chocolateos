#define COLOR_BG 0x2B1708
#define COLOR_FG 0xF3E5D0

static struct {
    uint32_t *fb;
    uint64_t width;
    uint64_t height;
    uint64_t pitch;
    uint32_t fg;
    uint32_t bg;
    uint32_t col;
    uint32_t row;
    uint32_t cols;
    uint32_t rows;
} con;

static void put_pixel(uint32_t x, uint32_t y, uint32_t color) {
    if (x >= con.width || y >= con.height) {
        return;
    }
    uint8_t *row = (uint8_t *)con.fb + y * con.pitch;
    ((uint32_t *)row)[x] = color;
}

static void draw_glyph(uint32_t col, uint32_t row, char c, uint32_t fg, uint32_t bg) {
    unsigned idx = 0;
    if (c >= 0x20 && c <= 0x7E) {
        idx = (unsigned)(c - 0x20);
    }
    uint32_t x0 = col * 8;
    uint32_t y0 = row * 16;
    for (uint32_t gy = 0; gy < 8; gy++) {
        uint8_t bits = font8x8[idx][gy];
        for (uint32_t gx = 0; gx < 8; gx++) {
            uint32_t color = (bits & (1u << gx)) ? fg : bg;
            put_pixel(x0 + gx, y0 + gy * 2, color);
            put_pixel(x0 + gx, y0 + gy * 2 + 1, color);
        }
    }
}

void console_set_color(uint32_t fg, uint32_t bg) {
    con.fg = fg;
    con.bg = bg;
}

void console_clear(void) {
    for (uint64_t y = 0; y < con.height; y++) {
        uint8_t *row = (uint8_t *)con.fb + y * con.pitch;
        for (uint64_t x = 0; x < con.width; x++) {
            ((uint32_t *)row)[x] = con.bg;
        }
    }
    con.col = 0;
    con.row = 0;
}

static void newline(void) {
    con.col = 0;
    con.row++;
    if (con.row >= con.rows) {
        /* Simple wrap to the top rather than a full scroll. */
        con.row = 0;
    }
}

void console_init(struct limine_framebuffer *fb) {
    con.fb = fb->address;
    con.width = fb->width;
    con.height = fb->height;
    con.pitch = fb->pitch;
    con.fg = COLOR_FG;
    con.bg = COLOR_BG;
    con.cols = (uint32_t)(con.width / 8);
    con.rows = (uint32_t)(con.height / 16);
    console_clear();
}

void console_putc(char c) {
    if (!con.fb) {
        return;
    }
    if (c == '\n') {
        newline();
        return;
    }
    if (c == '\r') {
        con.col = 0;
        return;
    }
    if (c == '\b') {
        if (con.col > 0) {
            con.col--;
            draw_glyph(con.col, con.row, ' ', con.fg, con.bg);
        }
        return;
    }
    if (c == '\t') {
        con.col = (con.col + 4) & ~3u;
        if (con.col >= con.cols) {
            newline();
        }
        return;
    }
    draw_glyph(con.col, con.row, c, con.fg, con.bg);
    con.col++;
    if (con.col >= con.cols) {
        newline();
    }
}

void console_write(const char *s) {
    while (*s) {
        console_putc(*s++);
    }
}
